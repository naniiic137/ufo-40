const char *const SDG_REGION_NAME[RG_COUNT] = {"THE SUNLIT SHELF", "GUMWELL", "FROND HOLLOW", "THE SUNKEN SHRINE",
                                               "LANTERN CAVE", "THE STILT PIT", "THE STILL ROOM", "THE RED DEEP"};

int sdg_region_at(int c, int r) {
    if (r < SDG_SURF_ROW + 1) return RG_SHELF;
    if (r >= 63) return RG_DEEP;
    if (c >= 56 && c <= 73 && r >= 52) return RG_STILL;
    if (c >= 70 && r >= 33) return RG_STILT;
    if (c <= 26 && r >= 36) return RG_LANTERN;
    if (c >= 26 && c <= 69 && r >= 26) return RG_SHRINE;
    if (c >= 68 && r < 33) return RG_HOLLOW;
    if (c < 30 && r < 36) return RG_GUMWELL;
    return RG_SHELF;
}

SdgMapIndex sdg_mi;

void sdg_map_index(void) {
    static bool done;
    if (done) return;
    done = true;
    memset(&sdg_mi, 0, sizeof sdg_mi);
    memset(sdg_mi.wall_of, -1, sizeof sdg_mi.wall_of);
    for (int r = 0; r < SDG_MH; r++)
        for (int c = 0; c < SDG_MW; c++) {
            char ch = SDG_MAP[r][c];
            SdgPlace p = {(int16_t)c, (int16_t)r};
            switch (ch) {
            case 'C':
            case 'c':
                if (sdg_mi.nchest < SDG_CHESTS) {
                    sdg_mi.chest_hidden[sdg_mi.nchest] = ch == 'c';
                    sdg_mi.chest[sdg_mi.nchest++] = p;
                }
                break;
            case 'H': if (sdg_mi.nhead < SDG_HEADS) sdg_mi.head[sdg_mi.nhead++] = p; break;
            case 'L': if (sdg_mi.nlore < SDG_LORES) sdg_mi.lore[sdg_mi.nlore++] = p; break;
            case 'P': sdg_mi.lever[LV_WEST] = p; break;
            case 'Q': sdg_mi.lever[LV_SHORT] = p; break;
            case 'Y': sdg_mi.lever[LV_FINAL_W] = p; break;
            case 'Z': sdg_mi.lever[LV_FINAL_E] = p; break;
            case 'I': sdg_mi.warden = p; break;
            case 'G': sdg_mi.gloam = p; break;
            case 'X':
                /* cracked rock: a cell joins the group of a cracked neighbour above or left */
                if (c > 0 && sdg_mi.wall_of[r][c - 1] >= 0) sdg_mi.wall_of[r][c] = sdg_mi.wall_of[r][c - 1];
                else if (r > 0 && sdg_mi.wall_of[r - 1][c] >= 0) sdg_mi.wall_of[r][c] = sdg_mi.wall_of[r - 1][c];
                else if (sdg_mi.nwall < SDG_WALLS) sdg_mi.wall_of[r][c] = (int8_t)sdg_mi.nwall++;
                break;
            default:
                if (ch >= 'a' && ch <= 'z' && ch != 'c' && sdg_mi.nspawn < SDG_MOBS) {
                    sdg_mi.spawn[sdg_mi.nspawn].letter = (uint8_t)ch;
                    sdg_mi.spawn[sdg_mi.nspawn].c = (int16_t)c;
                    sdg_mi.spawn[sdg_mi.nspawn].r = (int16_t)r;
                    sdg_mi.nspawn++;
                }
                break;
            }
        }
}
