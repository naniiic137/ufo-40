static void ledge_at(const LedgeDef *d, int t, int *x, int *y) {
    *x = d->x;
    *y = d->y;
    if (d->mv == MV_NONE) return;
    int off = hoop_tri(t + d->phase * d->period / 256, d->period, d->range);
    if (d->mv == MV_SIDE) *x += off;
    else *y += off;
}

void hoop_ledges_place(Match *m) {
    const ArenaDef *a = &HOOP_ARENA[m->arena];
    m->nledges = a->nledges;
    for (int i = 0; i < a->nledges; i++) {
        Ledge *l = &m->ledge[i];
        ledge_at(&a->ledge[i], m->t, &l->x, &l->y);
        l->w = a->ledge[i].w;
        l->dx = l->dy = 0;
    }
}

void hoop_ledges_update(Match *m) {
    const ArenaDef *a = &HOOP_ARENA[m->arena];
    if (m->test_ledges) {
        for (int i = 0; i < m->nledges; i++) m->ledge[i].dx = m->ledge[i].dy = 0;
        return;
    }
    for (int i = 0; i < m->nledges; i++) {
        Ledge *l = &m->ledge[i];
        int nx, ny;
        ledge_at(&a->ledge[i], m->t, &nx, &ny);
        l->dx = nx - l->x;
        l->dy = ny - l->y;
        l->x = nx;
        l->y = ny;
    }
}
