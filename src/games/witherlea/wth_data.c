const char *wth_item_name(int it) {
    if (it == I_CROSSBOW && wth_flag(F_BOW_LOADED)) return "LOADED CROSSBOW";
    if (it == I_LAMP && wth_flag(F_LAMP_LIT)) return "LAMP (LIT)";
    if (it == I_LAMP && wth_flag(F_LAMP_FILLED)) return "LAMP (FILLED)";
    if (it == I_SMOKER && wth_flag(F_SMOKER_LIT)) return "SMOKER (LIT)";
    if (it == I_SMOKER && wth_flag(F_SMOKER_LOADED)) return "SMOKER (LOADED)";
    if (it == I_SPRAYER && wth.s.mix) return "SPRAYER (MIXING)";
    return it > 0 && it < I_COUNT ? WTH_ITEM[it].name : "";
}

