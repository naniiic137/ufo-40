bool wth_room_dark(int r) {
    return (r >= R_LANDING && r <= R_ATTIC && r != R_BALCONY) || r == R_CELLAR;
}

bool wth_room_outside(int r) {
    return r == R_POND || r == R_GARDEN || r == R_YARD || r == R_DRIVE || r == R_COURTYARD || r == R_MAZE ||
           r == R_HEART || r == R_BALCONY;
}

