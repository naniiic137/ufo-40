/* HAT TRICK - the forty screens and the versus pitch. All drawn for UFO 40.
 *
 * Each screen is written as its left half (20 of 40 columns) and mirrored,
 * creatures and all, so every screen is the same on both sides, as two
 * kids need. Row 0 is the top, row 20 the bottom; a wall tile missing at an
 * edge means the screen wraps there.
 *   #  wall or block         =  a ledge: jump up through it, land on top
 *   P  where the kid on the left starts (its feet on the tile below)
 *   O  the ball's spot (on the middle line)
 *   *  the hidden dessert spot (not mirrored)
 *   a b c  the world's three kinds of creature; A B C the same kinds
 *          starting the other way (a buoy along instead of down, a glove up)
 *   X  the world's boss, on the middle line   Y  the Lido's chair
 *   G  the versus pitch's goal mouths (only the ball goes in) */
