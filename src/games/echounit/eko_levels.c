int eko_isqrt(int v) {
    if (v <= 0) return 0;
    int r = 0, bit = 1 << 30;
    while (bit > v) bit >>= 2;
    while (bit) {
        if (v >= r + bit) { v -= r + bit; r = (r >> 1) + bit; }
        else r >>= 1;
        bit >>= 2;
    }
    return r;
}

int eko_dist(int dx, int dy) {
    if (iabs(dx) > 30000 || iabs(dy) > 30000) return 30000;
    return eko_isqrt(dx * dx + dy * dy);
}

int eko_dir_to(int dx, int dy) {
    if (!dx && !dy) return 0;
    int best = 0;
    long bd = -2147483647L;
    for (int a = 0; a < EKO_ANG; a++) {
        long d = (long)dx * eko_cos(a) + (long)dy * eko_sin(a);
        if (d > bd) { bd = d; best = a; }
    }
    return best;
}

int eko_angdiff(int a, int b) {
    int d = (a - b) & 63;
    return d > 32 ? 64 - d : d;
}

