/* ROOFCAT - the whole town, one continuous chase: four areas of thirteen
 * hand-built screens, then the harbour arena. Original layouts.
 *
 * Every screen is 10 rows x 20 columns and starts and ends on a rooftop at
 * row 6, so the screens chain seamlessly. At the scroll speed a screen takes
 * about 10.7 seconds to pass, so the 52 screens take about nine minutes.
 *
 * Tiles:  #  building   w  window     d  door      O  dome       C  chimney
 *         =  ledge / awning / plank (one-way)       ^  broken glass (deadly)
 *         ~  sea water (deadly)       H  boat hull  M  merlon     B  fort brick
 *         T  lamp post (decor)
 * Things: *  a block of four snacks (bonus stretches only)
 *         1  paper lantern (shoot it for a life)
 *         !  a hidden spot: standing here calls down a lost letter
 * Foes:   p  pigeon       P  racing pigeon  c  crow (on a chimney)
 *         g  gecko        u  gull           L  spike lamp   K  moving spike lamp
 *         f  flying fish (in the water)     J  jumping jar (from the water)
 *         a  wasp (comes in from the left edge, at this height)
 *         n  snail (on a floor, or under a ledge)          t  toad
 *         e  pelican      j  jumping jar    x  firecracker  s  spider
 *         q  magpie       F  flasher
 * The second loop swaps some of these, see roofcat.c. */
