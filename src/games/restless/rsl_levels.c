/* RESTLESS - the three stages, each in two halves, drawn screen by screen
 * (20 x 12 tiles). All layouts are our own.
 *
 * Tiles:   .  air          #  rock         B  temple stone   D  bridge deck
 *          =  plank (jump up through it; DOWN + jump drops through)
 *          -  log (a plank over the falls)  F  fire-breathing face (solid)
 *          S  spear launcher (solid)       b  the button that fires them
 *          ~  water's surface  w  water, falls  %  leaves  I  trunk, pillar
 * Things:  P  start   |  section start (a pit sends you back here)
 *          T  torch   W  weapon torch      E  egg torch    x  hidden spot
 *          L  lift (across)  V  lift (up and down)  :  where a lift turns
 *          R  falling rock   X  the boss   Q  a bell lying  K  a clock lying
 *          Z  the way out of a treasure room
 * Foes:    q lackey  p spitbloom  e starspitter  h hive  a gnat  v wisps
 *          m tumblers  t toad hole  o boulderkin  c shellcrab  l leaper
 *          d weeper  k shade  g gloomcrow  n firemaw  z shieldling  u hulk
 *          (lackeys also climb out of the ground anywhere, all the time)
 * Marks for the demo player, never seen:  ! jump  ^ jump straight up
 *          < >  walk this way  ,  wait for the lift   _  a pit (bottom row)
 *          Y  the writing on a pit's wall */
